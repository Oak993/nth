"""Extract data tables from the archived approved IR-3. Offline; no source edits."""
import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path
sys.dont_write_bytecode = True
root = Path(__file__).resolve().parents[2]
source = root / 'porting/first-release/design-src/models-palette/auto-colour/hardening/r3/intensity_r3.py'
spec = importlib.util.spec_from_file_location('marrow_ir3_pack_rules', source)
ir3 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ir3)
keys = ['MAKER_PALETTE', 'SEED_MAKER', 'LINEUP_KEY', 'EFFORT_LADDER', 'EFFORT_SYNONYMS',
        'GENERIC_DOWN', 'GENERIC_UP', 'MAKER_LADDER', 'FAMILY', 'MODIFIER', 'FAMILY_UP',
        'FAMILY_DOWN', 'LEGACY_DAYS', 'SPEED_DOWN', 'SPLIT_DAYS']
rules = {key: getattr(ir3, key) for key in keys}
rules['HARNESS_REWRITES'] = [(rx.pattern, replacement) for rx, replacement in ir3.HARNESS_REWRITES]
rules['source_sha256'] = hashlib.sha256(source.read_bytes()).hexdigest()
body = json.dumps(rules, sort_keys=True, indent=2, ensure_ascii=True)
code = ('// PORT-ONLY: generated byte-derived IR-3 data tables, OD-0063/0066; ED-NEW-models-palette-11.\n'
        'using System.Text.Json;\nnamespace Marrow.Core.Port.ModelsPalette;\n'
        'public static class PaletteRuleData\n{\n'
        '    public static JsonElement Value {get;}=JsonDocument.Parse("""\n' + body +
        '\n""").RootElement.Clone();\n}\n')
target = root / 'src/Marrow.Core/Port/ModelsPalette/PaletteRuleData.cs'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if target.read_bytes() != code.encode('utf-8'):
        raise SystemExit('IR-3 pack rule data differs from the archived source')
    print('PASS: complete IR-3 data tables and source SHA-256 match')
else:
    target.write_bytes(code.encode('utf-8'))
    print('Wrote ' + str(target.relative_to(root)))

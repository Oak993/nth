using System.Text.Json;
using Marrow.App.Port.FirstRun;
using Marrow.App.Port.Voice;
using Marrow.App.Tests.Fixtures;

namespace Marrow.App.Tests.Port.FirstRun;

// WV-1 (OD-0098 welcome-voice pick, Words V2 "Warm"; the amendment naming where the model is changed): the words are wv_lib.py's V2, byte for byte, through the fixture tests/fixtures/welcome-voice/v2.json (generated by gen_v2.py).
public sealed class WelcomeVoiceWordsTests
{
    private static JsonElement Fixture() => JsonDocument.Parse(File.ReadAllBytes(StrikeFixtures.FixturePath("welcome-voice", "v2.json"))).RootElement;

    private static readonly (VoiceQuestionState State, string Key, string[] Fields)[] Layers =
    [
        (VoiceQuestionState.Ask, "ask", ["t", "b", "yes", "no"]),
        (VoiceQuestionState.Yes, "yes", ["t", "b"]),
        (VoiceQuestionState.Ready, "ready", ["t", "b"]),
        (VoiceQuestionState.No, "no", ["t", "b"]),
        (VoiceQuestionState.Slow, "slow", ["t", "b", "live_t", "live_d", "acc_t", "acc_d", "foot"]),
        (VoiceQuestionState.SlowLive, "slowlive", ["t", "b"]),
        (VoiceQuestionState.SlowAcc, "slowacc", ["t", "b"]),
    ];

    [Fact]
    [Trait("Feature", "WV-1")]
    [Trait("Decision", "ED-289")]
    public void The_words_equal_the_V2_fixture_byte_for_byte()
    {
        var words = Fixture().GetProperty("words");
        Assert.Equal("Warm", words.GetProperty("name").GetString());
        foreach (var (state, key, fields) in Layers)
            foreach (var field in fields)
                Assert.Equal(words.GetProperty(key).GetProperty(field).GetString(), WelcomeVoiceWords.Template(state, field)); // ordinal: byte for byte, the curly apostrophes included
    }

    [Fact]
    [Trait("Feature", "WV-1")]
    [Trait("Decision", "ED-289")]
    public void The_section_is_titled_Voice_typing_and_the_path_is_the_speech_model_page()
    {
        Assert.Equal("Voice typing", WelcomeVoiceWords.Title);
        Assert.Equal(WelcomeVoiceWords.SettingsPath, Fixture().GetProperty("path").GetString());
        Assert.Equal("Settings > Voice typing > Speech model", WelcomeVoiceWords.SettingsPath);
    }

    [Fact]
    [Trait("Feature", "WV-1")]
    [Trait("Decision", "ED-289")]
    public void Every_state_but_ask_and_slow_names_the_settings_path_in_its_body()
    {
        foreach (var state in new[] { VoiceQuestionState.Yes, VoiceQuestionState.Ready, VoiceQuestionState.No, VoiceQuestionState.SlowLive, VoiceQuestionState.SlowAcc })
            Assert.Contains(WelcomeVoiceWords.SettingsPath, WelcomeVoiceWords.Body(state, "874 MB", "264 MB"), StringComparison.Ordinal);
        Assert.Contains(WelcomeVoiceWords.SettingsPath, WelcomeVoiceWords.Foot(VoiceQuestionState.Slow), StringComparison.Ordinal);
    }

    [Fact]
    [Trait("Feature", "WV-1")]
    [Trait("Decision", "ED-289")]
    public void The_placeholders_are_filled_and_a_template_that_needs_an_unknown_size_gives_nothing()
    {
        Assert.Equal("Nth can turn your voice into text, right here on your PC. It needs a one-time 874 MB download.", WelcomeVoiceWords.Body(VoiceQuestionState.Ask, "874 MB", null));
        Assert.Null(WelcomeVoiceWords.Body(VoiceQuestionState.Ask, null, "264 MB"));
        Assert.Equal("Uses a smaller model (264 MB more). It hears languages other than English less well, Hindi and Urdu most.", WelcomeVoiceWords.Details(VoiceQuestionState.Slow, "264 MB")[0]);
        Assert.Null(WelcomeVoiceWords.Details(VoiceQuestionState.Slow, null)[0]);
        Assert.DoesNotContain('{', WelcomeVoiceWords.Body(VoiceQuestionState.Yes, null, null)!);
    }

    [Fact]
    [Trait("Feature", "WV-1")]
    [Trait("Decision", "ED-289")]
    public void The_buttons_are_in_the_order_the_design_draws_them_and_the_other_states_have_none()
    {
        Assert.Equal(["Maybe later", "Yes, set it up"], WelcomeVoiceWords.Choices(VoiceQuestionState.Ask));
        Assert.Equal(["See my words as I speak", "Get every word right"], WelcomeVoiceWords.Choices(VoiceQuestionState.Slow));
        foreach (var state in new[] { VoiceQuestionState.Yes, VoiceQuestionState.Ready, VoiceQuestionState.No, VoiceQuestionState.SlowLive, VoiceQuestionState.SlowAcc, VoiceQuestionState.Gone })
            Assert.Empty(WelcomeVoiceWords.Choices(state));
        Assert.Null(WelcomeVoiceWords.Heading(VoiceQuestionState.Gone));
        Assert.Null(WelcomeVoiceWords.Body(VoiceQuestionState.Gone, "874 MB", "264 MB"));
    }

    [Fact]
    [Trait("Feature", "WV-1")]
    [Trait("Decision", "ED-289")]
    public async Task The_sizes_the_words_name_are_the_models_the_scripted_pcs_would_get()
    {
        var pc = VoiceQuestionRig.Pc();
        Assert.Equal("874 MB", pc.Question.Mb);
        Assert.Null(pc.Question.SmallMb); // nothing stored yet
        var slow = VoiceQuestionRig.Slow();
        Assert.Equal("574 MB", slow.Question.Mb);
        await slow.Question.YesAsync(null, CancellationToken.None);
        Assert.Equal("264 MB", slow.Question.SmallMb); // the smaller rung a live answer installs
    }
}

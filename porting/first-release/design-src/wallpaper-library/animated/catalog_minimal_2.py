# walls/<id>.glsl. See OPTIONS-FORMAT.md for dynamic, perspective, focus and match. Match accent keeps the offsets the
# catalogue would derive from the first pack, and lowers the dark-theme chroma of the ground slots (dc 0.7), so that a warm
# accent gives a quiet dark ground instead of a brown one.
from wallpaper_kit import wall, dyn

# Match accent in dark mode: a warm accent (orange through yellow) must never give a brown or olive ground. The proposed
# host rule, carried as data on every entry here (match['dark_warm']), acts on the accent pack's DARK palette only:
#   w = smoothstep(band[0], band[1], h) * (1 - smoothstep(band[2], band[3], h)), h the slot's hue in degrees, taken in
#   -180..180 so the red end of the band (maroon, the other brown) is caught too;
#   a slot whose dark-role lightness is below ground_below turns toward ground_hue (plum) by w, along the shortest way;
#   a slot below mid_below turns toward mid_hue (rose) by w * mid_amount; both gain chroma (x 1 + (kc - 1) * w) and
#   lightness (+ dl * w);
#   a brighter slot (a light, a core, a highlight) keeps the accent's warm hue but is lifted by bright_dl * w and its
#   chroma multiplied by 1 + (bright_kc - 1) * w, so a dark gold reads as gold, not khaki.
# The light palette is never changed.
